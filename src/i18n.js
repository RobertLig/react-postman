export function getLocale() {
  if (typeof navigator === "undefined") return "en";
  const preferredLanguages = Array.isArray(navigator.languages) && navigator.languages.length
    ? navigator.languages
    : [navigator.language || "en"];
  const supportedLanguage = preferredLanguages
    .map((language) => language.toLowerCase().split("-")[0])
    .find((language) => language === "pl" || language === "en");
  return supportedLanguage || "en";
}

export function translate(text, locale = getLocale()) {
  if (typeof text !== "string" || locale !== "pl") return text;
  const normalized = text.trim();
  const leading = text.slice(0, text.length - text.trimStart().length);
  const trailing = text.slice(text.trimEnd().length);
  let translated = translations.pl[normalized];

  if (!translated) {
    let match = normalized.match(/^(\d+) (ad|ads)$/);
    if (match) {
      const count = Number(match[1]);
      const form = count === 1 ? "ogłoszenie"
        : count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 12 || count % 100 > 14)
          ? "ogłoszenia"
          : "ogłoszeń";
      translated = `${count} ${form}`;
    }
  }
  if (!translated) {
    const dynamicPatterns = [
      [/^Search radius \((km|mi)\)$/, (_, unit) => `Promień wyszukiwania (${unit})`],
      [/^(Minimum|Maximum) (width|height|length) \((cm|in)\)$/, (_, bound, dimension, unit) => {
        const bounds = bound === "Minimum" ? "Minimalna" : "Maksymalna";
        const dimensions = { width: "szerokość", height: "wysokość", length: "długość" };
        return `${bounds} ${dimensions[dimension]} (${unit})`;
      }],
      [/^(Minimum|Maximum) weight filter \((kg|lb)\)$/, (_, bound, unit) =>
        `${bound === "Minimum" ? "Minimalna" : "Maksymalna"} waga (${unit})`],
      [/^Stop (\d+): (.*)$/, (_, number, place) => `Przystanek ${number}: ${place}`],
      [/^View (.*)$/, (_, title) => `Zobacz ${title}`],
      [/^Move (stop|photo) (\d+) (up|down)$/, (_, item, number, direction) =>
        `Przesuń ${item === "stop" ? "przystanek" : "zdjęcie"} ${number} ${direction === "up" ? "w górę" : "w dół"}`],
      [/^Route (\d+)$/, (_, number) => `Trasa ${number}`],
      [/^(stop|photo) (\d+) order$/, (_, item, number) =>
        `Kolejność ${item === "stop" ? "przystanku" : "zdjęcia"} ${number}`],
      [/^(\d+) stops?$/, (_, rawCount) => {
        const count = Number(rawCount);
        const form = count === 1 ? "przystanek"
          : count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 12 || count % 100 > 14)
            ? "przystanki"
            : "przystanków";
        return `${count} ${form}`;
      }],
      [/^(.*) is typing$/, (_, name) => `${name === "They" ? "Ktoś" : name} pisze`],
      [/^Location lookup failed \((\d+)\)\.$/, (_, status) => `Nie udało się znaleźć lokalizacji (${status}).`],
      [/^File upload failed \((\d+)\)$/, (_, status) => `Wysyłanie pliku nie powiodło się (${status}).`],
      [/^Welcome(?:, (.*))?!$/, (_, name) => name ? `Witaj, ${name}!` : "Witaj!"],
      [/^Your account was deleted, but the sign-out cookie could not be cleared: (.*)$/, (_, error) =>
        `Konto zostało usunięte, ale nie udało się usunąć pliku cookie wylogowania: ${error}`],
      [/^Starting city: (.*)$/, (_, place) => `Miasto początkowe: ${place}`],
      [/^Starting point: (.*)$/, (_, place) => `Punkt początkowy: ${place}`],
      [/^Destination city: (.*)$/, (_, place) => `Miasto docelowe: ${place}`],
      [/^Destination: (.*)$/, (_, place) => `Cel podróży: ${place}`],
      [/^Pinned location \((.*)\)$/, (_, coordinates) => `Zaznaczone miejsce (${coordinates})`],
      [/^Hide conversation with (.*)$/, (_, name) => `Ukryj rozmowę z ${name}`],
      [/^Block (.*)\? They will no longer be able to message you\.$/, (_, name) => `Zablokować użytkownika ${name}? Nie będzie już mógł wysyłać Ci wiadomości.`],
      [/^Preview of (.*)$/, (_, name) => `Podgląd: ${name}`],
      [/^Remove (.*)$/, (_, name) => `Usuń ${name}`],
      [/^React (.*)$/, (_, reaction) => `Reaguj: ${reaction}`],
      [/^(.*) exceeds the 5 MB limit\.$/, (_, name) => `${name} przekracza limit 5 MB.`],
      [/^(.*) has an unsupported file type\.$/, (_, name) => `${name} ma nieobsługiwany typ pliku.`],
      [/^(.*) is not a JPG or PNG image\.$/, (_, name) => `${name} nie jest obrazem JPG ani PNG.`],
      [/^Your ad is live, but some photos failed: (.*)$/, (_, details) => `Ogłoszenie jest już widoczne, ale nie udało się dodać niektórych zdjęć: ${details}`],
    ];
    for (const [pattern, replacement] of dynamicPatterns) {
      const match = normalized.match(pattern);
      if (match) {
        translated = normalized.replace(pattern, replacement);
        break;
      }
    }
  }

  return translated ? `${leading}${translated}${trailing}` : text;
}

const LOCALIZED_ATTRIBUTES = ["alt", "aria-label", "placeholder", "title"];

export function LocalizedText({ children }) {
  return React.Children.map(children, (child) => {
    if (typeof child === "string") return translate(child);
    if (!React.isValidElement(child)) return child;
    if (child.props["data-no-translate"]) return child;
    const props = {};
    for (const attribute of LOCALIZED_ATTRIBUTES) {
      if (typeof child.props[attribute] === "string") {
        props[attribute] = translate(child.props[attribute]);
      }
    }
    if (child.props.children !== undefined) {
      props.children = <LocalizedText>{child.props.children}</LocalizedText>;
    }
    return React.cloneElement(child, props);
  });
}
